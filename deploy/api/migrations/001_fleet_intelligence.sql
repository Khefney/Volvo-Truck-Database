-- Fleet intelligence migration. Safe to re-run. Does not drop tables.
-- Simulated VINs use the SIM- prefix and are not Volvo VINs.
-- Reading coordinates are demo positions around the North Carolina Piedmont.

CREATE TABLE IF NOT EXISTS vehicles (
  id TEXT PRIMARY KEY,
  vin TEXT,
  chassis_series TEXT,
  chassis_number TEXT,
  country_of_origin TEXT,
  make TEXT,
  model TEXT,
  model_key TEXT,
  model_year INTEGER,
  powertrain TEXT,
  engine TEXT,
  horsepower INTEGER,
  torque INTEGER,
  location_label TEXT,
  source TEXT NOT NULL DEFAULT 'simulated',
  created_at TEXT,
  updated_at TEXT
);

CREATE TABLE IF NOT EXISTS vehicle_readings (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  vehicle_id TEXT NOT NULL,
  external_reading_id TEXT,
  timestamp TEXT NOT NULL,
  odometer_km REAL,
  energy_level_percent REAL,
  fuel_level_percent REAL,
  latitude REAL,
  longitude REAL,
  speed_kph REAL,
  operational_status TEXT,
  source TEXT NOT NULL DEFAULT 'simulated',
  created_at TEXT,
  UNIQUE (vehicle_id, external_reading_id)
);

CREATE INDEX IF NOT EXISTS idx_readings_vehicle_time ON vehicle_readings (vehicle_id, timestamp);

CREATE TABLE IF NOT EXISTS parameter_metadata (
  parameter_id TEXT PRIMARY KEY,
  name TEXT,
  parameter_type TEXT,
  unit TEXT,
  description TEXT,
  source TEXT,
  updated_at TEXT
);

CREATE TABLE IF NOT EXISTS raw_parameter_values (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  vehicle_id TEXT,
  reading_id INTEGER,
  parameter_id TEXT,
  value_json TEXT,
  timestamp TEXT,
  source TEXT
);

CREATE TABLE IF NOT EXISTS assumptions (
  key TEXT PRIMARY KEY,
  label TEXT,
  value REAL,
  unit TEXT,
  source_url TEXT,
  source_name TEXT,
  updated_at TEXT,
  notes TEXT
);

